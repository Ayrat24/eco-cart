using System;
using UnityEngine;

namespace Eco.Scripts.World
{
    [CreateAssetMenu(fileName = "WorldVisualSettings", menuName = "Eco/World Visual Settings")]
    public sealed class WorldVisualSettings : ScriptableObject
    {
        [SerializeField] private bool distortionEnabled = true;
        [Tooltip("Apparent planet radius in world units. Larger values make the world look flatter. This does not change map size.")]
        [SerializeField, Min(25)] private float worldRadius = 41.666668f;
        [Tooltip("Multiplier for the world bend. Zero is flat; one uses the radius above; two doubles the bend.")]
        [SerializeField, Range(0, 2)] private float distortionStrength = 1;
        [Tooltip("Radius around the player that stays flat for close interactions.")]
        [SerializeField, Min(0)] private float flatRadius = 6;

        [Header("Atmosphere")]
        [SerializeField] private bool atmosphereEnabled = true;
        [SerializeField] private Color atmosphereHorizonColor = new Color(0.48f, 0.76f, 1f);
        [SerializeField] private Color atmosphereSpaceColor = new Color(0.06f, 0.22f, 0.55f);
        [SerializeField, Range(0, 1)] private float atmosphereStrength = 0.85f;
        [Tooltip("Apparent width of the sky glow in degrees. Independent of terrain height and triangle depth; scene depth keeps it off objects and water.")]
        [SerializeField, Range(0.1f, 20)] private float atmosphereThickness = 4;
        [Tooltip("Falloff shape within the rim. The effect is always zero outside its thickness.")]
        [SerializeField, Range(0.5f, 3)] private float atmosphereSoftness = 1.3f;

        [Header("Terrain")]
        [Tooltip("Blends randomly offset texture samples to hide repetition. Zero restores regular tiling; one gives the full effect.")]
        [SerializeField, Range(0, 1)] private float terrainAntiTiling = 1;
        [Tooltip("Subtle brightness and warm/cool variation across broad patches of ground. Zero disables it.")]
        [SerializeField, Range(0, 0.5f)] private float terrainColourVariation = 0.16f;
        [Tooltip("Size of the broad ground colour patches in metres. Does not change the detail texture's scale.")]
        [SerializeField, Min(1)] private float terrainColourPatchSize = 22;

        [Header("Soil Surface Detail")]
        [Tooltip("Packed linear soil data: RG height gradient, B cavity. Generated by Eco/Rendering/Rebuild Soil Detail Texture.")]
        [SerializeField] private Texture2D soilDetailTexture;
        [Tooltip("Dirt channel in the terrain's first four layers. The current world uses layer 0; grass uses layer 1.")]
        [SerializeField, Range(0, 3)] private int soilLayerIndex;
        [Tooltip("Strength of shallow pore and soil-clump lighting. Zero disables the relief.")]
        [SerializeField, Range(0, 2)] private float soilReliefStrength = 0.85f;
        [Tooltip("Darkening inside pores. Keep low for dry soil.")]
        [SerializeField, Range(0, 0.5f)] private float soilCavityStrength = 0.22f;
        [Tooltip("World size of one soil-detail tile in metres. Includes larger pores and a finer grain layer.")]
        [SerializeField, Min(0.1f)] private float soilDetailSize = 2.4f;
        [Tooltip("Distance from the camera where detail disappears. Tiny features also fade automatically when too small on screen.")]
        [SerializeField, Min(1)] private float soilDetailFadeDistance = 35;

        [Header("Scrap Ground")]
        [Tooltip("Packed linear data: R grime, GB outline warp, A outline fray. Generated by Eco/Rendering/Rebuild Scrap Ground Texture.")]
        [SerializeField] private Texture2D scrapGroundTexture;
        [Tooltip("The cracks and tar of the dead ground under scrap. Keep it out of the greens: green means healthy here.")]
        [SerializeField] private Color scrapGroundDark = new Color(0.45f, 0.45f, 0.46f);
        [Tooltip("The crust of the dead ground under scrap. The tint multiplies it, so near white shows the type's colour as it is.")]
        [SerializeField] private Color scrapGroundLight = new Color(0.97f, 0.97f, 0.97f);
        [Tooltip("How far each stain takes on the colour of its scrap's type. Zero leaves all of them plain grey.")]
        [SerializeField, Range(0, 1)] private float scrapGroundTint = 0.85f;
        [Tooltip("How completely the dead ground replaces the natural ground.")]
        [SerializeField, Range(0, 1)] private float scrapGroundStrength = 0.95f;
        [Tooltip("How far a stain reaches from its scrap in metres, where it has faded out completely. Read when a game starts.")]
        [SerializeField, Range(0.5f, 6)] private float scrapStainRadius = 2.2f;
        [Tooltip("How much of the radius the stain's edge fades over. One fades all the way from the centre; low values leave a solid middle and a harder edge.")]
        [SerializeField, Range(0, 1)] private float scrapStainSoftness = 1;
        [Tooltip("How far the stain's outline wanders in metres.")]
        [SerializeField, Range(0, 2)] private float scrapGroundWarp = 0.35f;
        [Tooltip("World size of one tile of the dead ground's texture in metres. Not the stain's size: that is Scrap Stain Radius.")]
        [SerializeField, Min(0.1f)] private float scrapGroundSize = 4;
        [Tooltip("Smoothness of the dead ground. Low reads as dry and lifeless.")]
        [SerializeField, Range(0, 1)] private float scrapGroundSmoothness = 0.05f;
        [Tooltip("Seconds the ground takes to heal once its scrap is picked up.")]
        [SerializeField, Min(0.01f)] private float scrapGroundHealTime = 1.2f;

        public event Action Changed;
        public float WorldRadius => worldRadius;
        public float DistortionStrength => distortionStrength;
        public float Curvature => distortionEnabled ? distortionStrength / (2 * Mathf.Max(25, worldRadius)) : 0;
        public float FlatRadius => flatRadius;
        public bool AtmosphereEnabled => atmosphereEnabled;
        public Color AtmosphereHorizonColor => atmosphereHorizonColor;
        public Color AtmosphereSpaceColor => atmosphereSpaceColor;
        public float AtmosphereStrength => atmosphereStrength;
        public float AtmosphereThickness => atmosphereThickness;
        public float AtmosphereSoftness => atmosphereSoftness;
        public Vector4 TerrainVariation => new Vector4(terrainAntiTiling, terrainColourVariation,
            1 / Mathf.Max(1, terrainColourPatchSize), 0);
        public Texture2D SoilDetailTexture => soilDetailTexture;
        public Vector4 SoilDetail => soilDetailTexture != null
            ? new Vector4(soilReliefStrength, soilCavityStrength, 1 / Mathf.Max(0.1f, soilDetailSize), soilDetailFadeDistance)
            : new Vector4(0, 0, 1, 1);
        public Vector4 SoilLayerMask
        {
            get
            {
                var mask = Vector4.zero;
                mask[Mathf.Clamp(soilLayerIndex, 0, 3)] = 1;
                return mask;
            }
        }

        public Texture2D ScrapGroundTexture => scrapGroundTexture;
        public Vector4 ScrapGround => new Vector4(1 / Mathf.Max(0.1f, scrapGroundSize),
            scrapGroundTexture != null ? scrapGroundStrength : 0, scrapGroundWarp, scrapStainSoftness);
        public float ScrapStainRadius => scrapStainRadius;
        public Vector4 ScrapGroundFade => new Vector4(1 / Mathf.Max(0.01f, scrapGroundHealTime), 0, 0, 0);
        public float ScrapGroundTint => scrapGroundTint;
        public Vector4 ScrapGroundDark => (Vector4)scrapGroundDark.linear;
        public Vector4 ScrapGroundLight
        {
            get
            {
                Vector4 light = scrapGroundLight.linear;
                light.w = scrapGroundSmoothness;
                return light;
            }
        }

        public void InitializeFromCurvature(float curvature, float interactionRadius)
        {
            worldRadius = curvature > 0 ? Mathf.Max(25, 1 / (2 * curvature)) : 41.666668f;
            distortionStrength = Mathf.Clamp(curvature * 2 * worldRadius, 0, 2);
            flatRadius = Mathf.Max(0, interactionRadius);
            Changed?.Invoke();
        }

        private void OnValidate()
        {
            worldRadius = Mathf.Max(25, worldRadius);
            distortionStrength = Mathf.Clamp(distortionStrength, 0, 2);
            flatRadius = Mathf.Max(0, flatRadius);
            atmosphereStrength = Mathf.Clamp01(atmosphereStrength);
            atmosphereThickness = Mathf.Clamp(atmosphereThickness, 0.1f, 20);
            atmosphereSoftness = Mathf.Clamp(atmosphereSoftness, 0.5f, 3);
            terrainAntiTiling = Mathf.Clamp01(terrainAntiTiling);
            terrainColourVariation = Mathf.Clamp(terrainColourVariation, 0, 0.5f);
            terrainColourPatchSize = Mathf.Max(1, terrainColourPatchSize);
            soilLayerIndex = Mathf.Clamp(soilLayerIndex, 0, 3);
            soilReliefStrength = Mathf.Clamp(soilReliefStrength, 0, 2);
            soilCavityStrength = Mathf.Clamp(soilCavityStrength, 0, 0.5f);
            soilDetailSize = Mathf.Max(0.1f, soilDetailSize);
            soilDetailFadeDistance = Mathf.Max(1, soilDetailFadeDistance);
            scrapGroundSize = Mathf.Max(0.1f, scrapGroundSize);
            scrapGroundHealTime = Mathf.Max(0.01f, scrapGroundHealTime);
            Changed?.Invoke();
        }
    }
}
